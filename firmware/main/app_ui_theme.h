#pragma once

/* Color roles are encoded in the display's RGB565 format. */
#define UI_RGB565(r, g, b) ((((r) & 0xf8) << 8) | (((g) & 0xfc) << 3) | ((b) >> 3))

enum {
    UI_CANVAS = UI_RGB565(0, 0, 0),
    UI_SURFACE = UI_RGB565(24, 24, 24),
    UI_ENGAGED = UI_RGB565(40, 40, 40),
    UI_GUIDE = UI_RGB565(112, 112, 112),
    UI_TEXT = UI_RGB565(244, 244, 244),
    UI_SECONDARY = UI_RGB565(184, 184, 184),
    UI_ACCENT = UI_RGB565(239, 139, 72),
    UI_SESSION_RUNNING = UI_RGB565(159, 188, 208),
    UI_SESSION_DONE = UI_RGB565(155, 187, 164),
    UI_SESSION_FAILED = UI_RGB565(206, 154, 147),
};

enum {
    UI_SPACE = 8,
    UI_INSET = 2 * UI_SPACE,
    UI_LEFT_MARGIN = 4 * UI_SPACE,
    UI_TITLE_BASELINE = 28,
    UI_CONTENT_TOP = 56,
    UI_FOOTER_DESCENT = 6,
};

/* These roles index the faces generated by scripts/build_ui_font.py. */
typedef enum {
    UI_FONT_HINT,
    UI_FONT_BODY,
    UI_FONT_TITLE,
} ui_font_t;
